export interface TaskValidationContext {
  state: InfobaseState;
  lastQueryResult: QueryResultTable | null;
  lastQueryText: string;
  lastBSLResult: BSLExecutionResult | null;
  lastBSLCode: string;
}

export function validateAcademyTask(
  task: AcademyTask,
  ctx: TaskValidationContext
): { passed: boolean; message: string } {
  const { state, lastQueryResult, lastQueryText, lastBSLResult, lastBSLCode } = ctx;

  switch (task.id) {
    case 'task-01-catalog-cp': {
      if (state.counterparties.length >= 5) {
        const latest = state.counterparties[state.counterparties.length - 1];
        const cleanInn = latest.inn.replace(/\D/g, '');
        if (cleanInn.length === 10 || cleanInn.length === 12) {
          return {
            passed: true,
            message: `Отлично! Контрагент «${latest.name}» (ИНН ${latest.inn}) записан в справочник Контрагенты.`,
          };
        }
        return {
          passed: false,
          message: `Контрагент добавлен, но его ИНН («${latest.inn}») должен состоять из 10 или 12 цифр!`,
        };
      }
      return {
        passed: false,
        message: `Сейчас в справочнике Контрагенты ${state.counterparties.length} элем. Создайте еще минимум одного контрагента с корректным ИНН.`,
      };
    }

    case 'task-02-catalog-nom': {
      const goodsWith20 = state.nomenclature.filter(
        (n) => n.type === 'Товар' && n.vatRate === '20%' && n.salePrice > 0
      );
      if (state.nomenclature.length >= 6 && goodsWith20.length >= 3) {
        return {
          passed: true,
          message: 'Превосходно! Новая карточка товара со счетом учета 41.01 и ставкой НДС 20% добавлена в Номенклатуру.',
        };
      }
      return {
        passed: false,
        message: `В справочнике Номенклатура сейчас ${state.nomenclature.length} поз. Добавьте новую позицию с видом «Товар», НДС «20%» и ценой продажи > 0.`,
      };
    }

    case 'task-03-doc-receipt': {
      const postedReceipts = state.documents.filter(
        (d) => d.docType === 'ПоступлениеТоваровУслуг' && d.posted && !d.markedForDeletion
      );
      if (postedReceipts.length >= 2) {
        return {
          passed: true,
          message: `Отлично! Проведено документов Поступления: ${postedReceipts.length}. Движения Дт 41.01 Кт 60.01 и приход на склад сформированы!`,
        };
      }
      return {
        passed: false,
        message: `Найдено проведенных документов Поступления: ${postedReceipts.length} (требуется минимум 2). Создайте и проведите новую приходную накладную в разделе «Покупки».`,
      };
    }

    case 'task-04-doc-sale': {
      const postedSales = state.documents.filter(
        (d) => d.docType === 'РеализацияТоваровУслуг' && d.posted && !d.markedForDeletion
      );
      if (postedSales.length >= 2) {
        return {
          passed: true,
          message: `Супер! Проведено документов Реализации: ${postedSales.length}. Списана себестоимость (90.02.1), отражена выручка (90.01.1) и начислен НДС (90.03 — 68.02)!`,
        };
      }
      return {
        passed: false,
        message: `Проведенных документов Реализации: ${postedSales.length} (нужно минимум 2). Создайте и проведите реализацию в разделе «Продажи».`,
      };
    }

    case 'task-05-payroll-osv': {
      const postedPayroll = state.documents.filter(
        (d) => d.docType === 'НачислениеЗарплаты' && d.posted && !d.markedForDeletion
      );
      const has70Entry = state.accountingEntries.some((e) => e.creditAccount === '70' || e.debitAccount === '70');
      if (postedPayroll.length >= 1 && has70Entry) {
        return {
          passed: true,
          message: 'Блестяще! Зарплата начислена, удержан НДФЛ 13% (счет 68.01) и начислены страховые взносы 30% (счет 69.09).',
        };
      }
      return {
        passed: false,
        message: 'Создайте и проведите документ «Начисление зарплаты» в разделе «Зарплата и кадры».',
      };
    }

    case 'task-06-query-select': {
      if (!lastQueryResult || lastQueryResult.error) {
        return { passed: false, message: 'Сначала выполните запрос без ошибок в «Консоли запросов» Конфигуратора!' };
      }
      const qLow = lastQueryText.toLowerCase();
      if (
        qLow.includes('справочник.номенклатура') &&
        qLow.includes('где') &&
        lastQueryResult.rows.length > 0
      ) {
        return {
          passed: true,
          message: `Запрос выполнен верно! Отобрано позиций номенклатуры: ${lastQueryResult.rows.length}.`,
        };
      }
      return {
        passed: false,
        message: 'Запрос должен обращаться к таблице `Справочник.Номенклатура`, содержать условие `ГДЕ ЦенаПродажи > 20000` и возвращать строки.',
      };
    }

    case 'task-07-query-virtual-balances': {
      if (!lastQueryResult || lastQueryResult.error) {
        return { passed: false, message: 'Выполните запрос в «Консоли запросов» Конфигуратора.' };
      }
      const qLow = lastQueryText.toLowerCase();
      if (qLow.includes('регистрнакопления.товарынаскладах.остатки') && lastQueryResult.rows.length > 0) {
        return {
          passed: true,
          message: `Виртуальная таблица остатков освоена! Получено складских позиций: ${lastQueryResult.rows.length}.`,
        };
      }
      return {
        passed: false,
        message: 'Обратитесь в запросе к виртуальной таблице `РегистрНакопления.ТоварыНаСкладах.Остатки` и нажмите «Выполнить запрос».',
      };
    }

    case 'task-08-query-group-by': {
      if (!lastQueryResult || lastQueryResult.error) {
        return { passed: false, message: 'Сначала выполните запрос в «Консоли запросов»!' };
      }
      const qLow = lastQueryText.toLowerCase();
      if (
        qLow.includes('регистрбухгалтерии.хозрасчетный') &&
        qLow.includes('сгруппировать по') &&
        qLow.includes('сумма(') &&
        lastQueryResult.rows.length > 0
      ) {
        return {
          passed: true,
          message: `Агрегатный запрос к регистру бухгалтерии выполнен! Сгруппировано счетов: ${lastQueryResult.rows.length}.`,
        };
      }
      return {
        passed: false,
        message: 'Используйте `РегистрБухгалтерии.Хозрасчетный`, конструкцию `СГРУППИРОВАТЬ ПО` и агрегатную функцию `СУММА(...)`.',
      };
    }

    case 'task-09-bsl-vat-func': {
      if (!lastBSLResult || !lastBSLResult.success) {
        return { passed: false, message: 'Запустите код модуля BSL без синтаксических ошибок (кнопка «Запустить код F5»).' };
      }
      const hasFunc = /функция\s+/i.test(lastBSLCode);
      const has60000 = lastBSLResult.output.some((line) => line.includes('60000'));
      if (hasFunc && has60000) {
        return {
          passed: true,
          message: 'Отлично! Ваша функция на встроенном языке 1С корректно рассчитала сумму с НДС (60 000 руб.).',
        };
      }
      return {
        passed: false,
        message: 'Код должен содержать объявление `Функция ... КонецФункции` и выводить через `Сообщить()` рассчитанную сумму `60000`.',
      };
    }

    case 'task-10-bsl-collections': {
      if (!lastBSLResult || !lastBSLResult.success) {
        return { passed: false, message: 'Сначала выполните код BSL в Конфигураторе!' };
      }
      const hasVT = /новый\s+таблицазначений/i.test(lastBSLCode) && /\.итог\s*\(/i.test(lastBSLCode);
      if (hasVT && lastBSLResult.output.length >= 2) {
        return {
          passed: true,
          message: 'Замечательно! Вы создали ТаблицуЗначений, заполнили строки в памяти и посчитали итог по колонке!',
        };
      }
      return {
        passed: false,
        message: 'Создайте `Новый ТаблицаЗначений`, вызовите метод `.Итог("Сумма")` и выведите строки через `Сообщить()`.',
      };
    }

    case 'task-11-bsl-query-loop': {
      if (!lastBSLResult || !lastBSLResult.success) {
        return { passed: false, message: 'Запустите модуль BSL в Конфигураторе!' };
      }
      const codeLow = lastBSLCode.toLowerCase();
      const hasQueryPattern =
        codeLow.includes('новый запрос') &&
        codeLow.includes('справочник.сотрудники') &&
        codeLow.includes('выбрать()') &&
        codeLow.includes('следующий()');
      if (hasQueryPattern && lastBSLResult.output.length >= 2) {
        return {
          passed: true,
          message: 'Вы освоили главный паттерн разработчика 1С: программный запрос и обход выборки курсором!',
        };
      }
      return {
        passed: false,
        message: 'Используйте `Новый Запрос` к `Справочник.Сотрудники`, методы `.Выполнить().Выбрать()` и цикл `Пока Выборка.Следующий() Цикл`.',
      };
    }

    case 'task-12-config-metadata': {
      const totalCustom = state.customCatalogs.length + state.customDocuments.length;
      if (totalCustom >= 1 && [...state.customCatalogs, ...state.customDocuments].some(o => o.attributes.length >= 1)) {
        const createdName =
          state.customCatalogs[0]?.name || state.customDocuments[0]?.name || 'Объект';
        return {
          passed: true,
          message: `Поздравляем с прохождением курса! Объект метаданных «${createdName}» сохранён в учебном дереве метаданных!`,
        };
      }
      return {
        passed: false,
        message: 'В Конфигураторе нажмите «+ Объект» в дереве метаданных и создайте собственный Справочник или Документ.',
      };
    }

    default:
      return { passed: false, message: 'Неизвестное задание' };
  }
}
